"""Turn Giovanni GLDAS area-averaged CSV exports into yearly series for the app (src/data/gldas.ts).

Usage: python3 scripts/build_gldas.py <folder with Giovanni GLDAS CSVs>

Each CSV is one variable over a small box around one of the five cities. The city is found from the
box centre and the variable from the column name, so file names do not matter. Monthly GLDAS values
become yearly totals (runoff, evaporation) or yearly means (soil moisture), in millimetres.
"""
import csv, glob, json, os, re, sys
from collections import defaultdict
from calendar import monthrange

CITIES = {  # city key in src/data/cities.ts -> (name, lat, lon)
    'power': ('Metro Manila', 14.6, 121.0), 'naga': ('Naga', 13.62, 123.19), 'tug': ('Tuguegarao', 17.61, 121.73),
    'cebu': ('Metro Cebu', 10.32, 123.89), 'cdo': ('Cagayan de Oro', 8.48, 124.65),
}

# GLDAS Noah monthly variable -> (app id, label, how to make a yearly value, definition)
KNOWN = {
    'Qs_acc': ('runoff', 'Surface runoff, NASA GLDAS model', 'acc3h',
               'Rain that runs off the ground surface instead of soaking in, in mm per year.'),
    'Qsb_acc': ('baseflow', 'Underground runoff, NASA GLDAS model', 'acc3h',
                'Water that drains through the soil into streams, in mm per year.'),
    'Evap_tavg': ('evap', 'Evaporation, NASA GLDAS model', 'flux',
                  'Water returned to the air from soil, water and plants, in mm per year.'),
    'SoilMoi0_10cm_inst': ('soil10', 'Topsoil moisture (0–10 cm), NASA GLDAS model', 'mean',
                           'Water held in the top 10 cm of soil, in mm of water depth (yearly average).'),
    'Rainf_f_tavg': ('grain', 'Rainfall, NASA GLDAS model', 'flux',
                     'Rain falling on the ground, in mm per year, as used to drive the GLDAS land model.'),
}

def read(path):
    with open(path, newline='') as f:
        rows = list(csv.reader(f))
    meta = {r[0].rstrip(':'): r[1] for r in rows if len(r) >= 2 and r[0].endswith(':')}
    start = next(i for i, r in enumerate(rows) if r and r[0].strip() == 'time')
    col = rows[start][1].strip()
    fill = float(next((v for k, v in meta.items() if k.startswith('Fill Value')), '-9999.9'))
    vals = {}
    for r in rows[start + 1:]:
        if len(r) < 2 or not r[1].strip():
            continue
        v = float(r[1])
        if v != fill:
            vals[r[0][:7]] = v  # "YYYY-MM"
    w, s, e, n = map(float, meta['User Bounding Box'].split(','))
    return col, ((s + n) / 2, (w + e) / 2), vals

def nearest_city(lat, lon):
    key = min(CITIES, key=lambda k: (CITIES[k][1] - lat) ** 2 + (CITIES[k][2] - lon) ** 2)
    d = ((CITIES[key][1] - lat) ** 2 + (CITIES[key][2] - lon) ** 2) ** 0.5
    return key if d < 1.0 else None

def yearly(vals, how):
    by = defaultdict(dict)
    for ym, v in vals.items():
        by[int(ym[:4])][int(ym[5:7])] = v
    out = {}
    for y, months in by.items():
        if len(months) < 12:
            continue  # skip incomplete years
        if how == 'mean':
            out[y] = sum(months.values()) / 12
        elif how == 'flux':  # kg m-2 s-1 == mm/s
            out[y] = sum(v * 86400 * monthrange(y, m)[1] for m, v in months.items())
        else:  # acc3h: monthly mean of 3-hourly accumulations (kg m-2 == mm)
            out[y] = sum(v * 8 * monthrange(y, m)[1] for m, v in months.items())
    return out

def main(folder):
    series, variables = [], {}
    for path in sorted(glob.glob(os.path.join(folder, '*.csv'))):
        col, (lat, lon), vals = read(path)
        name = next((k for k in KNOWN if col.endswith(k)), None)
        city = nearest_city(lat, lon)
        if not name or not city:
            print(f'skip {os.path.basename(path)}: column {col!r}, box centre {lat:.2f},{lon:.2f}')
            continue
        vid, label, how, definition = KNOWN[name]
        ys = yearly(vals, how)
        years = sorted(ys)
        series.append({'id': f'{city}-{vid}', 'region': CITIES[city][0], 'source': 'NASA GLDAS Noah land model (via Giovanni)',
                       'kind': 'Land model', 'variable': vid, 'unit': 'mm', 'years': years,
                       'values': [round(ys[y], 1) for y in years],
                       'note': f'{definition} Monthly GLDAS values over a small box around {CITIES[city][0]}, exported from NASA Giovanni.'})
        prev = variables.get(vid, {'from': years[0], 'to': years[-1]})
        variables[vid] = {'label': label, 'short': label.split(',')[0], 'unit': 'mm', 'group': 'Water on land (GLDAS)',
                          'from': min(prev['from'], years[0]), 'to': max(prev['to'], years[-1])}
        print(f'{CITIES[city][0]:15s} {vid:9s} {years[0]}–{years[-1]} ({len(years)} years)')
    ts = ('// Generated by scripts/build_gldas.py from NASA Giovanni GLDAS exports. Do not edit by hand.\n'
          "import type { Series } from './series';\nimport type { VarDef } from './variables';\n\n"
          f'export const GLDAS_VARS: Record<string, VarDef> = {json.dumps(variables, ensure_ascii=False, indent=2)};\n\n'
          f'export const GLDAS_SERIES: Series[] = {json.dumps(series, ensure_ascii=False, indent=2)};\n')
    open(os.path.join(os.path.dirname(__file__), '..', 'src', 'data', 'gldas.ts'), 'w').write(ts)
    print(f'wrote src/data/gldas.ts: {len(series)} series, {len(variables)} variables')

if __name__ == '__main__':
    main(sys.argv[1])
